// Builds test/icons.js (a small subset of Material Design Icons, Apache-2.0) for the harness.
// Usage: (in a scratch dir with @mdi/js installed)  node make-icons.cjs /path/to/test/icons.js
const mdi = require('@mdi/js');
const names = `sofa home-outline thermometer water-percent power power-off alert-circle-outline close
chevron-right arrow-oscillating rotate-right rotate-left arrow-up arrow-down stop ceiling-fan ceiling-fan-light
fan fan-off lightbulb lightbulb-outline lamp floor-lamp ceiling-light led-strip-variant blinds blinds-open
window-shutter window-shutter-open toggle-switch-variant toggle-switch-variant-off power-socket-us
check-circle-outline close-circle-outline desk-lamp television coffee-maker bed motion-sensor string-lights
wall-sconce-flat chandelier water-boiler robot-vacuum desk monitor sleep door mirror bed-outline
toilet shower-head fireplace speaker heat-wave air-purifier light-recessed vanity-light theme-light-dark
radiator silverware-fork-knife outdoor-lamp coach-lamp pine-tree palm-tree flower`.split(/\s+/).filter(Boolean);
const out = {};
for (const n of names) {
  const key = 'mdi' + n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
  if (mdi[key]) out['mdi:' + n] = mdi[key];
  else console.error('missing', n);
}
require('fs').writeFileSync(process.argv[2],
  '// Generated by make-icons.cjs: a subset of Material Design Icons (Apache-2.0, pictogrammers.com).\n' +
  'window.GH_TEST_ICONS = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log('wrote', Object.keys(out).length, 'icons');
